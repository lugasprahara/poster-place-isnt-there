#!/usr/bin/env python3
"""Extract glyph outlines from a TTF as flattened polylines for embedding in font.ts.
Uses fontTools only. Flattens quadratic/cubic curves to >=12 segments each.
"""
import json, sys, os

FONT_PATH = "/usr/share/fonts/truetype/noto/NotoSerifDisplay-Black.ttf"
if not os.path.exists(FONT_PATH):
    FONT_PATH = "/usr/share/fonts/truetype/dejavu/DejaVuSerif-Bold.ttf"

CHARS = list("ACEHILMNORSTUW") + [" "]
SEG = 16

from fontTools.ttLib import TTFont
from fontTools.pens.basePen import BasePen

def quad(p0, p1, p2, n=SEG):
    pts = []
    for i in range(1, n + 1):
        t = i / n
        mt = 1 - t
        x = mt*mt*p0[0] + 2*mt*t*p1[0] + t*t*p2[0]
        y = mt*mt*p0[1] + 2*mt*t*p1[1] + t*t*p2[1]
        pts.append((round(x, 1), round(y, 1)))
    return pts

def cubic(p0, p1, p2, p3, n=SEG):
    pts = []
    for i in range(1, n + 1):
        t = i / n
        mt = 1 - t
        x = mt**3*p0[0] + 3*mt*mt*t*p1[0] + 3*mt*t*t*p2[0] + t**3*p3[0]
        y = mt**3*p0[1] + 3*mt*mt*t*p1[1] + 3*mt*t*t*p2[1] + t**3*p3[1]
        pts.append((round(x, 1), round(y, 1)))
    return pts

class FlattenPen(BasePen):
    def __init__(self, glyphSet):
        super().__init__(glyphSet)
        self.contours = []
        self.current = None
        self.cur = (0, 0)
    def _moveTo(self, p):
        self.current = [(round(p[0], 1), round(p[1], 1))]
        self.cur = p
    def _lineTo(self, p):
        self.current.append((round(p[0], 1), round(p[1], 1)))
        self.cur = p
    def _curveToOne(self, p1, p2, p3):
        self.current.extend(cubic(self.cur, p1, p2, p3))
        self.cur = p3
    def _qCurveToOne(self, p1, p2):
        self.current.extend(quad(self.cur, p1, p2))
        self.cur = p2
    def _closePath(self):
        if self.current:
            self.contours.append(self.current)
            self.current = None
    def _endPath(self):
        if self.current:
            self.contours.append(self.current)
            self.current = None

def main():
    font = TTFont(FONT_PATH)
    upem = font["head"].unitsPerEm
    glyphSet = font.getGlyphSet()
    cmap = font.getBestCmap()
    glyphs = {}
    for ch in CHARS:
        if ch == " ":
            gname = cmap.get(ord(" "), "space")
            adv = glyphSet[gname].width
            glyphs[ch] = {"advance": adv, "contours": []}
            continue
        gname = cmap[ord(ch)]
        g = glyphSet[gname]
        pen = FlattenPen(glyphSet)
        g.draw(pen)
        glyphs[ch] = {"advance": g.width, "contours": pen.contours}
        print(ch, gname, "adv", g.width, "contours", len(pen.contours), "pts", sum(len(c) for c in pen.contours))
    out = {"unitsPerEm": upem, "fontPath": FONT_PATH, "glyphs": glyphs}
    ts = "// Generated by tools/extract-font.py from " + FONT_PATH + "\n"
    ts += "export const FONT = " + json.dumps(out) + ";\n"
    dest = os.path.join(os.path.dirname(__file__), "..", "font.ts")
    with open(dest, "w") as f:
        f.write(ts)
    print("wrote", dest, "upem", upem)

if __name__ == "__main__":
    main()
